export interface AppInfo {
  // App Id
  id: string
  // From Channel
  channel: string
  // App Version
  version: string
  // App Version Code
  versionCode: string
  // App Build Code
  buildCode: string
  // App Build Type, e.g. release
  buildType: string
  // Package Id, e.g. com.netease.cloudmusic
  packageId: string
  // Product id
  pid: string
  // App Urs Id, URS_APPID
  urs: string
}
